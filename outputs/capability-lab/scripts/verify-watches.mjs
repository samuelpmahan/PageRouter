#!/usr/bin/env node
// Real-browser acceptance check for synchronized watch controls, views, and replay.
import assert from 'node:assert/strict';
import { access, copyFile, mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const args=Object.fromEntries(process.argv.slice(2).map(arg=>{const [key,...rest]=arg.replace(/^--/,'').split('=');return[key,rest.join('=')||true];}));
const url=args.url||'http://127.0.0.1:4173';
const out=resolve(args.out||'/mnt/d/somefile/capability-lab/watch-browser-evidence');
const evidenceDir=resolve(args.evidence||resolve(dirname(fileURLToPath(import.meta.url)),'../evidence/watches-workbench/ui'));
await mkdir(out,{recursive:true});await mkdir(evidenceDir,{recursive:true});
const playwrightModule=process.env.CAPABILITY_LAB_PLAYWRIGHT_MODULE||'/mnt/c/Users/tenni/Documents/Codex/2026-10-07/yo/work/toolteam/browser/node_modules/playwright/index.mjs';
const browsersPath=process.env.CAPABILITY_LAB_BROWSERS_PATH||'/mnt/c/Users/tenni/Documents/Codex/2026-10-07/yo/work/toolteam/browser/browsers';
const browserDeps=process.env.CAPABILITY_LAB_LD_LIBRARY_DIR||'/mnt/c/Users/tenni/Documents/Codex/2026-10-07/yo/work/toolteam/browser/deps/usr/lib/x86_64-linux-gnu';
const chromiumExecutable=process.env.CAPABILITY_LAB_CHROMIUM_EXECUTABLE;
for(const [label,path,variable] of [['Playwright module',playwrightModule,'CAPABILITY_LAB_PLAYWRIGHT_MODULE'],['Playwright browser cache',browsersPath,'CAPABILITY_LAB_BROWSERS_PATH'],['browser shared-library directory',browserDeps,'CAPABILITY_LAB_LD_LIBRARY_DIR'],...(chromiumExecutable?[['Chromium executable',chromiumExecutable,'CAPABILITY_LAB_CHROMIUM_EXECUTABLE']]:[])])try{await access(path);}catch{throw new Error(`Browser verification prerequisite missing: ${label} at ${path}. Set ${variable} to an existing path; do not install dependencies for this check.`);}
process.env.PLAYWRIGHT_BROWSERS_PATH=browsersPath;
process.env.LD_LIBRARY_PATH=[browserDeps,process.env.LD_LIBRARY_PATH].filter(Boolean).join(':');
const {chromium}=await import(playwrightModule);
const canonical=value=>Array.isArray(value)?`[${value.map(canonical).join(',')}]`:value&&typeof value==='object'?`{${Object.keys(value).sort().map(k=>`${JSON.stringify(k)}:${canonical(value[k])}`).join(',')}}`:JSON.stringify(value);
let browser,page;const errors=[];
try {
  browser=await chromium.launch({headless:true,...(chromiumExecutable?{executablePath:chromiumExecutable}:{})});
  page=await browser.newPage({viewport:{width:1600,height:1100},deviceScaleFactor:1});
  page.on('pageerror',error=>errors.push(error.message));
  page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
  await page.goto(url,{waitUntil:'networkidle'});
  await page.waitForFunction(()=>window.watchLab?.getState&&document.querySelector('#watch-workbench'),{timeout:20000});
  await page.locator('[data-workspace-mode="watches"]').click();
  await page.waitForFunction(()=>document.querySelector('.workspace')?.classList.contains('watches-active'));
  await page.locator('[data-workspace-mode="foundations"]').click();
  await page.waitForFunction(()=>!document.querySelector('.workspace')?.classList.contains('watches-active'));
  const selectedFoundation=await page.locator('#capability-select').inputValue();
  await page.locator('[data-workspace-mode="watches"]').click();
  await page.waitForFunction(()=>document.querySelector('.workspace')?.classList.contains('watches-active'));
  assert.equal(await page.locator('#capability-select').inputValue(),selectedFoundation,'Watch mode preserves the Foundation capability selection');
  const initial=await page.evaluate(()=>window.watchLab.getState());
  const modelCounts=await page.locator('.watch-model-svg').count();
  assert.equal(modelCounts,3,'All three model diagrams must be present in the same view');
  const parts=await page.locator('.watch-model-svg [data-part-id]').count();
  assert.equal(parts,30,'All source-bound components must have selectable geometry');
  const pathCounts=await page.evaluate(()=>Object.fromEntries(['mechanical','quartz','software'].map(model=>[model,{energy:document.querySelectorAll(`[data-watch-model="${model}"] .energy-path:not([hidden])`).length,timing:document.querySelectorAll(`[data-watch-model="${model}"] .timing-path:not([hidden])`).length}])));
  assert.ok(pathCounts.mechanical.energy>0&&pathCounts.mechanical.timing>0,'Mechanical energy and timing paths remain distinct');
  assert.ok(pathCounts.quartz.energy>0&&pathCounts.quartz.timing>0,'Quartz energy and timing paths remain distinct');
  assert.equal(pathCounts.software.energy,0,'Software model does not invent an energy path');
  const poseZero=await page.evaluate(()=>window.watchLab.getGeometry(0,'mechanical.balanceWheel'));
  await page.locator('#watch-duration-numerator').fill('1');
  await page.locator('#watch-duration-denominator').fill('8');
  await page.locator('#watch-advance').click();
  const poseState=await page.evaluate(()=>window.watchLab.getState());
  const assembled=await page.evaluate(()=>window.watchLab.getGeometry(0,'mechanical.balanceWheel'));
  assert.equal(await page.locator('#watch-explode-value').innerText(),'0%','Assembled output label matches the zero slider value');
  const balanceAtZero=poseZero.watches[0].parts.find(part=>part.id==='mechanical.balanceWheel');
  const balanceAtBeat=assembled.watches[0].parts.find(part=>part.id==='mechanical.balanceWheel');
  assert.notDeepEqual(balanceAtBeat.strokes||balanceAtBeat.points,balanceAtZero.strokes||balanceAtZero.points,'Schematic oscillator pose changes at a distinct logical time');
  assert.equal(balanceAtBeat.motionSource?.status,'illustrative','Moving schematic exposes its state-bound illustrative motion source');
  await page.screenshot({path:resolve(out,'watches-assembled.png')});
  await page.locator('[data-part-id="mechanical.palletFork"]').first().focus();
  const focusedState=canonical(await page.evaluate(()=>window.watchLab.getState()));
  await page.keyboard.press('Space');
  assert.equal(canonical(await page.evaluate(()=>window.watchLab.getState())),focusedState,'Space on a focused component selects it without triggering global Play');
  const beforeView=canonical(await page.evaluate(()=>window.watchLab.getState()));
  await page.evaluate(()=>window.watchLab.setView({explode:1,selected:'mechanical.balanceWheel'}));
  assert.equal(await page.locator('#watch-explode-value').innerText(),'100%','Programmatic explosion updates the visible slider percentage');
  const exploded=await page.evaluate(()=>window.watchLab.getGeometry(1,'mechanical.balanceWheel'));
  const afterView=canonical(await page.evaluate(()=>window.watchLab.getState()));
  assert.equal(afterView,beforeView,'Explosion and selection must not change raw model state or replay history');
  const assembledBalance=assembled.watches[0].parts.find(part=>part.id==='mechanical.balanceWheel');
  const explodedBalance=exploded.watches[0].parts.find(part=>part.id==='mechanical.balanceWheel');
  assert.notDeepEqual(explodedBalance.center,assembledBalance.center,'Explosion changes rendered part positions');
  await page.screenshot({path:resolve(out,'watches-exploded.png')});
  await page.evaluate(()=>document.activeElement?.blur());
  const beforeKeyboardStep=await page.evaluate(()=>window.watchLab.getState());
  await page.keyboard.press('.');
  const keyboardStepped=await page.evaluate(()=>window.watchLab.getState());
  assert.equal(keyboardStepped.counters.mechanicalBeats,beforeKeyboardStep.counters.mechanicalBeats+1,'Period steps the selected event when focus is outside controls');

  await page.locator('#watch-step-event').selectOption('mechanicalBeat');
  const beforeButtonStep=await page.evaluate(()=>window.watchLab.getState());
  await page.locator('#watch-step').click();
  const stepped=await page.evaluate(()=>window.watchLab.getState());
  assert.ok(canonical(stepped)!==canonical(initial),'Selected-event step changes the actual raw model state');
  assert.equal(stepped.counters.mechanicalBeats,beforeButtonStep.counters.mechanicalBeats+1,'One mechanical beat step increments one beat');
  const replay=await page.evaluate(()=>window.watchLab.replay());
  assert.equal(replay.exact,true,'Replay canonical full state and events must match');
  assert.equal(replay.matches,true,'Replay result must expose canonical match');

  await page.locator('#watch-pause').click();
  assert.equal((await page.evaluate(()=>window.watchLab.getState())).paused,true,'Pause control records paused state');
  await page.locator('#watch-resume').click();
  assert.equal((await page.evaluate(()=>window.watchLab.getState())).paused,false,'Resume control records active state');
  const beforeAdvance=await page.evaluate(()=>window.watchLab.getState());
  await page.locator('#watch-duration-numerator').fill('1');
  await page.locator('#watch-duration-denominator').fill('2');
  await page.locator('#watch-advance').click();
  const advanced=await page.evaluate(()=>window.watchLab.getState());
  assert.equal(advanced.time.numerator/advanced.time.denominator-beforeAdvance.time.numerator/beforeAdvance.time.denominator,0.5,'Rational advance adds the requested shared logical time');
  await page.locator('.watch-microscope summary').first().click();
  const rangeSelect=page.locator('#watch-microscope');
  const rangeOptions=await rangeSelect.locator('option').evaluateAll(options=>options.map(option=>({value:option.value,text:option.textContent})));
  const softwareRange=rangeOptions.find(option=>option.text.includes('softwareUpdate'));
  assert.ok(softwareRange,'Microscope lists exact compact software update ranges');
  await rangeSelect.selectOption(softwareRange.value);
  await page.locator('#watch-microscope-offset').fill('0');
  await page.locator('#watch-expand-range').click();
  const expandedWindow=JSON.parse(await page.locator('#watch-expanded-range').innerText());
  assert.ok(expandedWindow.events.length<=32&&expandedWindow.events.length>0,'Microscope expands only a bounded page');
  await page.locator('#watch-energy-battery').uncheck();
  assert.equal((await page.evaluate(()=>window.watchLab.getState())).energy.battery,false,'Battery toggle is model state and recorded');
  await page.locator('#watch-energy-battery').check();
  assert.equal((await page.evaluate(()=>window.watchLab.getState())).energy.battery,true,'Battery can be restored explicitly');
  const beforeHidden=canonical(await page.evaluate(()=>window.watchLab.getState()));
  await page.evaluate(()=>window.watchLab.applyAction({type:'visibility',hidden:true}));
  const hiddenState=canonical(await page.evaluate(()=>window.watchLab.getState()));
  await page.locator('#watch-autoplay').click();
  await page.waitForTimeout(250);
  assert.equal(canonical(await page.evaluate(()=>window.watchLab.getState())),hiddenState,'Hidden play attempt leaves the model unchanged');
  assert.notEqual(beforeHidden,canonical(await page.evaluate(()=>window.watchLab.getState())),'Visibility itself is retained as an explicit model action');
  await page.evaluate(()=>window.watchLab.applyAction({type:'visibility',hidden:false}));
  await page.locator('#watch-autoplay').click();
  await page.waitForTimeout(360);
  await page.evaluate(()=>window.watchLab.stopAutoplay());
  const pacing=await page.evaluate(()=>window.watchLab.getPacing());
  assert.ok(pacing.count>=2&&pacing.count<=512,'Pacing retains a bounded set of actual callback gaps');
  await page.locator('#watch-measure-pacing').click();
  const pacingSummary=await page.evaluate(()=>window.watchLab.getPacing().summary);
  assert.ok(pacingSummary?.count>=2,'Pacing summary uses the statistics capability');
  await page.emulateMedia({reducedMotion:'reduce'});
  const motion=await page.locator('.watch-part .part-shape').first().evaluate(el=>getComputedStyle(el).transitionDuration);
  assert.equal(motion,'0s','Reduced-motion preference removes decorative transitions');
  const selectionBefore=canonical(await page.evaluate(()=>window.watchLab.getState()));
  await page.locator('[data-part-id="quartz.crystal"]').first().click();
  const selectedState=canonical(await page.evaluate(()=>window.watchLab.getState()));
  assert.equal(selectedState,selectionBefore,'Selecting a part remains render-only');
  assert.match(await page.locator('#watch-component-title').innerText(),/Quartz resonator/,'Selected label is bound to component source metadata');
  const fullReplay=await page.evaluate(()=>window.watchLab.replay());
  assert.equal(fullReplay.exact,true,'Full sequence replays to identical canonical state and events');
  const exportPromise=page.waitForEvent('download');
  await page.locator('#watch-export-run').click();
  const download=await exportPromise;await download.saveAs(resolve(out,'watch-run-export.json'));
  const beforeNewRun=await page.evaluate(()=>window.watchLab.getState());
  await page.locator('#watch-new-run').click();
  const newRun=await page.evaluate(()=>window.watchLab.getState());
  assert.equal(newRun.history.actions.length,0,'Start new run creates a fresh bounded history');
  assert.equal(canonical(await page.evaluate(()=>window.watchLab.getArchivedState())),canonical(beforeNewRun),'Previous run remains in the one-run archive');
  await page.locator('#watch-restore-archive').click();
  assert.equal(canonical(await page.evaluate(()=>window.watchLab.getState())),canonical(beforeNewRun),'Archived run can be restored intact');
  const report={url,initial:{paused:initial.paused,time:initial.time,counters:initial.counters},pose:{time:poseState.time,balanceMotionChanged:true,motionSource:balanceAtBeat.motionSource},models:modelCounts,selectableParts:parts,pathCounts,keyboard:{focusedSpaceLeavesStateUnchanged:true,periodBeatCount:keyboardStepped.counters.mechanicalBeats},step:{event:'mechanicalBeat',counter:stepped.counters.mechanicalBeats},advance:{time:advanced.time},microscope:{rangeCount:rangeOptions.length,expanded:expandedWindow.events.length},energy:{off:true,restored:true},pacing:{count:pacing.count,summary:pacingSummary},replay:{exact:fullReplay.exact,matches:fullReplay.matches,canonicalStateLength:fullReplay.canonicalState.length,canonicalEventsLength:fullReplay.canonicalEvents.length},archive:{newRunActions:newRun.history.actions.length,previousRunRetained:true,restored:true},explosionInvariant:true,selectionInvariant:true,reducedMotion:motion,exportedFile:resolve(out,'watch-run-export.json'),consoleErrors:errors,screenshots:[resolve(out,'watches-assembled.png'),resolve(out,'watches-exploded.png')]};
  await writeFile(resolve(out,'watches-replay-evidence.json'),JSON.stringify({originalState:await page.evaluate(()=>window.watchLab.getState()),replayedState:fullReplay.state,canonicalState:fullReplay.canonicalState,canonicalEvents:fullReplay.canonicalEvents,exact:fullReplay.exact},null,2)+'\n');
  assert.deepEqual(errors,[],'No browser page or console errors');
  await writeFile(resolve(out,'watches-browser-report.json'),JSON.stringify(report,null,2)+'\n');
  for(const filename of ['watches-assembled.png','watches-exploded.png','watches-replay-evidence.json','watches-browser-report.json','watch-run-export.json'])await copyFile(resolve(out,filename),resolve(evidenceDir,filename));
  console.log(JSON.stringify(report,null,2));
} catch(error) {
  const report={url,error:error?.stack||String(error),consoleErrors:errors};
  try {if(page&&page.url()!=='about:blank')await page.screenshot({path:resolve(out,'watches-failed.png'),fullPage:true});} catch{}
  await writeFile(resolve(out,'watches-browser-failure.json'),JSON.stringify(report,null,2)+'\n');
  console.error(JSON.stringify(report,null,2));throw error;
} finally {await browser?.close();}
